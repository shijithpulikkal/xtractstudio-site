"""Refresh js/posts.js from the Xtract Studio Hashnode blog.

Run by .github/workflows/update-blog-posts.yml (daily, or on demand).
Uses only the Python standard library. Tries the Hashnode GraphQL API
first and falls back to the RSS feed. Leaves the existing file alone
if both fail or return nothing, so the site never loses its posts.
"""
import html
import json
import os
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET
from datetime import datetime, timezone
from email.utils import parsedate_to_datetime

HOST = "xtractstudio.hashnode.dev"
OUT = os.path.join(os.path.dirname(__file__), "..", "js", "posts.js")
PREFIX = "window.XTRACT_POSTS = "
UA = {"User-Agent": "xtractstudio-site-blog-sync"}

QUERY = """query($host:String!,$first:Int!){publication(host:$host){posts(first:$first){edges{node{
  title brief url publishedAt readTimeInMinutes coverImage{url} tags{name}}}}}}"""


def from_graphql():
    body = json.dumps({"query": QUERY, "variables": {"host": HOST, "first": 50}}).encode()
    req = urllib.request.Request("https://gql.hashnode.com/", data=body,
                                 headers={**UA, "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as r:
        data = json.load(r)
    edges = data["data"]["publication"]["posts"]["edges"]
    return [e["node"] for e in edges]


def strip_tags(s):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", s or ""))).strip()


def from_rss():
    req = urllib.request.Request(f"https://{HOST}/rss.xml", headers=UA)
    with urllib.request.urlopen(req, timeout=30) as r:
        root = ET.fromstring(r.read())
    ns = {"content": "http://purl.org/rss/1.0/modules/content/"}
    posts = []
    for it in root.iter("item"):
        content = strip_tags(it.findtext("content:encoded", default="", namespaces=ns))
        enc = it.find("enclosure")
        posts.append({
            "title": it.findtext("title", "").strip(),
            "url": it.findtext("link", "").strip(),
            "publishedAt": parsedate_to_datetime(it.findtext("pubDate")).astimezone(timezone.utc).isoformat().replace("+00:00", "Z"),
            "readTimeInMinutes": max(1, round(len(content.split()) / 220)),
            "brief": strip_tags(it.findtext("description", ""))[:320],
            "coverImage": {"url": enc.get("url")} if enc is not None else None,
            "tags": [{"name": c.text.strip()} for c in it.findall("category") if c.text],
        })
    return posts


def main():
    posts = []
    for fn in (from_graphql, from_rss):
        try:
            posts = fn()
            if posts:
                print(f"{fn.__name__}: {len(posts)} posts")
                break
        except Exception as e:  # keep going to the next source
            print(f"{fn.__name__} failed: {e}", file=sys.stderr)
    if not posts:
        print("No posts fetched; keeping the existing file.")
        return

    posts.sort(key=lambda p: p["publishedAt"], reverse=True)
    old = []
    if os.path.exists(OUT):
        with open(OUT, encoding="utf-8") as f:
            text = f.read().strip()
        try:
            old = json.loads(text[text.index(PREFIX) + len(PREFIX):].rstrip(";")).get("posts", [])
        except ValueError:
            old = []
    if old == posts:
        print("No changes.")
        return

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    data = {"source": f"https://{HOST}/",
            "updatedAt": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "posts": posts}
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* Generated by scripts/update_posts.py. Do not edit by hand. */\n")
        f.write(PREFIX + json.dumps(data, indent=2, ensure_ascii=False) + ";\n")
    print("js/posts.js updated.")


if __name__ == "__main__":
    main()
